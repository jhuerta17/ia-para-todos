import assert from 'node:assert/strict';
import { PortalRepository, PRIVACY_VERSION } from '../netlify/lib/portal-repository.mts';
import { createPortalHandler } from '../netlify/functions/portal.mts';
import { NetlifyDB } from '@netlify/database-dev';
import { getDatabase } from '@netlify/database';
import { fileURLToPath } from 'node:url';
const local = new NetlifyDB({ logger: () => {} });
let pool;
try {
  const url = await local.start();
  await local.applyMigrations(fileURLToPath(new URL('../netlify/database/migrations', import.meta.url)));
  pool = getDatabase({ connectionString: url }).pool;
  await pool.query("INSERT INTO portal_profiles(user_id) VALUES ('fixture-A'),('fixture-B')");
  await pool.query("INSERT INTO portal_enrollments(user_id,course_id) VALUES ('fixture-A','first-prompt')");
  await assert.rejects(pool.query("INSERT INTO portal_lesson_progress(user_id,course_id,lesson_id) VALUES ('fixture-B','first-prompt','clear-request')"));
  await pool.query("INSERT INTO portal_lesson_progress(user_id,course_id,lesson_id) VALUES ('fixture-A','first-prompt','clear-request')");
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM portal_lesson_progress')).rows[0].n, 1);
  console.log('  ok migrations and enrollment ownership constraints');
  process.env.PORTAL_EMAIL_HASH_SECRET = 'local-test-secret-at-least-32-characters';
  const repo = new PortalRepository(pool);
  const A = { id: 'student-A', email: 'a@example.com', confirmedAt: '2026-01-01', roles: [] };
  const B = { ...A, id: 'student-B', email: 'b@example.com' };
  let user = null;
  const handler = createPortalHandler({ repository: () => repo, user: async () => user });
  const request = (path, method='GET', body) => handler(new Request(`https://test.example/api/portal/${path}`, { method, headers: { Origin: 'https://test.example', 'Content-Type':'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) }));
  assert.equal((await request('chats')).status, 401);
  user = { ...A, confirmedAt: undefined };
  assert.equal((await request('profile')).status, 403);
  user = A;
  assert.equal((await request('progress')).status, 428);
  assert.equal((await request('profile','POST',{ adult: true, privacyVersion: PRIVACY_VERSION })).status, 200);
  assert.equal((await request('progress','POST',{ action: 'complete', lessonId: 'clear-request' })).status, 409);
  await request('progress','POST',{ action:'enroll' });
  await request('progress','POST',{ action:'complete',lessonId:'clear-request' });
  await request('progress','POST',{ action:'complete',lessonId:'clear-request' });
  assert.deepEqual(await (await request('progress')).json(), { enrolled:true, completed:['clear-request'] });
  assert.equal((await request('progress','POST',{ action:'enroll',userId:B.id })).status, 400);
  const chat = await (await request('chats','POST')).json();
  assert.equal((await request(`chats/${chat.id}`)).status, 200);
  user = B;
  await request('profile','POST',{ adult:true,privacyVersion:PRIVACY_VERSION });
  assert.deepEqual(await (await request('progress')).json(), { enrolled:false,completed:[] });
  assert.equal((await request(`chats/${chat.id}`)).status, 404);
  assert.equal((await request(`chats/${chat.id}`,'DELETE')).status, 404);
  assert.deepEqual((await (await request('chats')).json()).chats, []);
  console.log('  ok authenticated APIs, confirmation, consent, progress idempotency, and two-user ownership');
  await pool.query('UPDATE portal_chats SET expires_at=now()-interval \'1 day\' WHERE id=$1',[chat.id]);
  user = A;
  assert.equal((await request(`chats/${chat.id}`)).status, 404);
  await repo.purge();
  assert.equal((await pool.query('SELECT * FROM portal_chats WHERE id=$1',[chat.id])).rowCount,0);
  await request('account','DELETE');
  assert.equal((await request('profile')).status,403);
  await repo.retryDeletions(async()=>{throw new Error('temporary identity failure');});
  assert.equal((await pool.query('SELECT completed_at FROM portal_deletion_jobs WHERE user_id=$1',[A.id])).rows[0].completed_at,null);
  await repo.retryDeletions(async()=>{});
  assert.ok((await pool.query('SELECT completed_at FROM portal_deletion_jobs WHERE user_id=$1',[A.id])).rows[0].completed_at);
  assert.equal((await request('profile')).status,403);
  console.log('  ok expired histories hidden and purged; account deletion retries and denies stale sessions');
  console.log('verify:portal:db: passed');
} finally { await pool?.end(); await local.stop(); }
